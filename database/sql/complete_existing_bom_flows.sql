CREATE OR REPLACE PROCEDURE PROJ1_2_GEN_COMP_BOM_SEMI_L1(
 P_SEMI_L1_SUB_CAT VARCHAR2, P_USER_LOGIN VARCHAR2, P_COMPONENID OUT VARCHAR2, P_ERROR OUT VARCHAR2
) IS
 n NUMBER; counter NUMBER; highest NUMBER; reserved VARCHAR2(1000); category VARCHAR2(100);
BEGIN
 SAVEPOINT GENERATE_M4;
 category:=TRIM(P_SEMI_L1_SUB_CAT);
 SELECT COUNT(*) INTO n FROM PROJ1_2_COMP_SEMI_L1_V WHERE TRIM(CODE_SUB_CAT)=category;
 IF n=0 OR LENGTH(category)<>4 THEN RAISE_APPLICATION_ERROR(-20010,'Invalid M4 product subcategory'); END IF;
 BEGIN
  INSERT INTO PROJ1_2_COMPONENT_COUNTER(CATEGORY_KEY,LAST_NUMBER) VALUES('M4:'||category,0);
 EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL;
 END;
 SELECT LAST_NUMBER INTO counter FROM PROJ1_2_COMPONENT_COUNTER WHERE CATEGORY_KEY='M4:'||category FOR UPDATE;
 SELECT MIN(MATERIAL_ID_M4_TMP) INTO reserved FROM PROJ1_2_DML_SEMI_L1_COMP_M4_TP t
 WHERE USER_CREATE_TMP=P_USER_LOGIN AND STATUS_USED IS NULL AND SUBSTR(MATERIAL_ID_M4_TMP,1,4)=category
 AND NOT EXISTS (SELECT 1 FROM PROJ1_2_DML_SEMI_L1_COMP_M4 m WHERE m.MATERIAL_ID_M4=t.MATERIAL_ID_M4_TMP)
 AND NOT EXISTS (SELECT 1 FROM PROJ1_2_DML_SEMI_L1_M4_COMP_M4 c WHERE c.COMP_M4_MATERIAL_ID_M4=t.MATERIAL_ID_M4_TMP);
 IF reserved IS NOT NULL THEN P_COMPONENID:=reserved; P_ERROR:=NULL; RETURN; END IF;
 SELECT NVL(MAX(v),0) INTO highest FROM (
  SELECT CASE WHEN REGEXP_LIKE(SUBSTR(MATERIAL_ID,5),'^[0-9]+$') THEN TO_NUMBER(SUBSTR(MATERIAL_ID,5)) END v FROM PROJ1_MATERIAL WHERE SUBSTR(MATERIAL_ID,1,4)=category
  UNION ALL SELECT CASE WHEN REGEXP_LIKE(SUBSTR(MATERIAL_ID_M4,5),'^[0-9]+$') THEN TO_NUMBER(SUBSTR(MATERIAL_ID_M4,5)) END FROM PROJ1_2_DML_SEMI_L1_COMP_M4 WHERE SUBSTR(MATERIAL_ID_M4,1,4)=category
  UNION ALL SELECT CASE WHEN REGEXP_LIKE(SUBSTR(COMP_M4_MATERIAL_ID_M4,5),'^[0-9]+$') THEN TO_NUMBER(SUBSTR(COMP_M4_MATERIAL_ID_M4,5)) END FROM PROJ1_2_DML_SEMI_L1_M4_COMP_M4 WHERE SUBSTR(COMP_M4_MATERIAL_ID_M4,1,4)=category
  UNION ALL SELECT CASE WHEN REGEXP_LIKE(SUBSTR(MATERIAL_ID_M4_TMP,5),'^[0-9]+$') THEN TO_NUMBER(SUBSTR(MATERIAL_ID_M4_TMP,5)) END FROM PROJ1_2_DML_SEMI_L1_COMP_M4_TP WHERE SUBSTR(MATERIAL_ID_M4_TMP,1,4)=category
 );
 counter:=GREATEST(counter,highest)+1;
 IF counter>99999 THEN RAISE_APPLICATION_ERROR(-20011,'M4 component number range exhausted'); END IF;
 UPDATE PROJ1_2_COMPONENT_COUNTER SET LAST_NUMBER=counter WHERE CATEGORY_KEY='M4:'||category;
 P_COMPONENID:=category||LPAD(TO_CHAR(counter),5,'0');
 INSERT INTO PROJ1_2_DML_SEMI_L1_COMP_M4_TP(MATERIAL_ID_M4_TMP,USER_CREATE_TMP,CREATE_DATE_TMP,STATUS_USED) VALUES(P_COMPONENID,P_USER_LOGIN,SYSDATE,NULL);
 P_ERROR:=NULL;
EXCEPTION WHEN OTHERS THEN ROLLBACK TO GENERATE_M4; P_COMPONENID:=NULL; P_ERROR:=SUBSTR(SQLERRM,1,2000);
END;
