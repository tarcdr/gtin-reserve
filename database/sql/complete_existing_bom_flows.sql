  SELECT COUNT(*) INTO n FROM PROJ1_2_DML_SEMI_L2_COMP_M5 WHERE TRIM(SEMI_FG_LV2_BOM_ID)=TRIM(P_SEMI_FG_LV2_BOM_ID) AND TRIM(MATERIAL_ID_M5)=TRIM(P_COMPONENT_ID);
  IF n>0 THEN RAISE_APPLICATION_ERROR(-20003,'Component is not editable'); END IF;
