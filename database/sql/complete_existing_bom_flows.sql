  VALUES(PROJ1_2_BOM_LINK_SEQ.NEXTVAL,P_COMPONENT_ID,P_SEARCH_DESC,P_COMP_DESC_EN,P_COMP_DESC_TH,P_SEMI_FG_LV2_BOM_ID,P_SITE,P_UOM,'INS',P_USER_ROLE,P_USER,SYSDATE,P_FG_BOM_ID,P_MATERIAL_ID_FG_1,P_SEMI_FG_LV2_ID);
 END IF;
 UPDATE PROJ1_2_DML_COMP_M5_TP SET STATUS_USED='SAVED',CREATE_DATE_TMP=SYSDATE WHERE MATERIAL_ID_M5_TMP=P_COMPONENT_ID AND USER_CREATE_TMP=P_USER;
