CREATE OR REPLACE VIEW PROJ1_2_SEMI_FG_LV1_ID_V AS
SELECT DISTINCT TRIM(i.SEMI_FG_LV1_ID) MATERIAL_ID, TRIM(i.DESC_SEMI_FG_LV1_ID) SEARCH_DESCRIPTION,
 TRIM(i.FULL_DESC_SEMI_FG_LV1_EN) FULL_DESCRIPTION_EN, TRIM(i.FULL_DESC_SEMI_FG_LV1_TH) FULL_DESCRIPTION_TH,
 TRIM(b.SEMI_FG_LV1_BOM_ID) BOM_ID, TRIM(b.DESC_SEMI_FG_LV1_BOM_ID) BOM_DESCRIPTION,
 TRIM(i.UOM_SEMI_FG_L1ID) UOM, TRIM(i.STATUS_ROW) STATUS_ROW,
 TRIM(i.MATTYPE_SEMI_FG_L1ID) MATTYPE, TRIM(i.SUB_MATTYPE_SEMI_FG_L1ID) SUB_MATTYPE,
 (SELECT MIN(TRIM(br.BRAND_ABB)) FROM PROJ1_BRAND br
  WHERE TRIM(br.BRAND)=TRIM(COALESCE((SELECT MIN(m.BRAND) FROM PROJ1_MATERIAL m WHERE TRIM(m.MATERIAL_ID)=TRIM(i.SEMI_FG_LV1_ID)),fg.BRAND))
     OR TRIM(br.BRAND_ABB)=TRIM(COALESCE((SELECT MIN(m.BRAND) FROM PROJ1_MATERIAL m WHERE TRIM(m.MATERIAL_ID)=TRIM(i.SEMI_FG_LV1_ID)),fg.BRAND))) BRAND_ABB
FROM PROJ1_2_DML_SEMI_L1_ID i
JOIN PROJ1_2_DML_SEMI_L1_BOM b ON TRIM(b.SEMI_FG_LV1_BOM_ID)=TRIM(i.SEMI_FG_LV1_BOM_ID) AND TRIM(b.FG_BOM_ID)=TRIM(i.FG_BOM_ID)
LEFT JOIN PROJ1_2_DML_FG_MATTYPE_1 fg ON TRIM(fg.MATERIAL_ID_FG_1)=TRIM(i.MATERIAL_ID_FG_1)
WHERE TRIM(i.SEMI_FG_LV1_ID) IS NOT NULL AND TRIM(b.SEMI_FG_LV1_BOM_ID) IS NOT NULL
/


