DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='PROJ1_2_COMPONENT_COUNTER';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE PROJ1_2_COMPONENT_COUNTER (CATEGORY_KEY VARCHAR2(100) PRIMARY KEY, LAST_NUMBER NUMBER NOT NULL)'; END IF;
END;
