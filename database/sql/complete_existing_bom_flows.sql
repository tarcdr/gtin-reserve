SELECT MAX(CASE WHEN REGEXP_LIKE(NO,'^[0-9]+$') THEN TO_NUMBER(NO) END) v FROM PROJ1_2_DML_SEMI_L2_BOM_EXIST
UNION ALL
SELECT MAX(CASE WHEN REGEXP_LIKE(NO,'^[0-9]+$') THEN TO_NUMBER(NO) END) v FROM PROJ1_2_DML_SEMI_L2_ID_EXIST
