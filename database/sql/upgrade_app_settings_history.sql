-- Oracle upgrade for an EXISTING PROJ1_2_APP_SETTINGS table.
-- Stop application writes / enable maintenance mode before running with F5.
-- DDL commits implicitly. Back up the table first; deploy the new app before
-- reopening access. Never run the old UPDATE-based app against history rows.
-- Repeatable: retains values, actors, timestamps, and existing history IDs.
DECLARE
    n PLS_INTEGER;
    max_id NUMBER;
    next_id NUMBER;
    pk_columns VARCHAR2(4000);
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'PROJ1_2_APP_SETTINGS';
    IF n = 0 THEN RAISE_APPLICATION_ERROR(-20001, 'Install create_app_settings.sql first'); END IF;

    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'PROJ1_2_APP_SETTINGS' AND COLUMN_NAME = 'ID';
    IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE PROJ1_2_APP_SETTINGS ADD (ID NUMBER(19,0))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'PROJ1_2_APP_SETTINGS' AND COLUMN_NAME = 'PREVIOUS_VALUE';
    IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE PROJ1_2_APP_SETTINGS ADD (PREVIOUS_VALUE VARCHAR2(1))'; END IF;

    EXECUTE IMMEDIATE 'SELECT NVL(MAX(ID), 0) FROM PROJ1_2_APP_SETTINGS' INTO max_id;
    SELECT COUNT(*) INTO n FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'PROJ1_2_APP_SETTINGS_SEQ';
    IF n = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE PROJ1_2_APP_SETTINGS_SEQ START WITH ' || TO_CHAR(max_id + 1, 'FM99999999999999999999') || ' INCREMENT BY 1 NOCACHE ORDER NOCYCLE';
    END IF;
    EXECUTE IMMEDIATE 'ALTER SEQUENCE PROJ1_2_APP_SETTINGS_SEQ NOCACHE ORDER NOCYCLE';
    EXECUTE IMMEDIATE 'SELECT PROJ1_2_APP_SETTINGS_SEQ.NEXTVAL FROM DUAL' INTO next_id;
    IF next_id <= max_id THEN
        EXECUTE IMMEDIATE 'ALTER SEQUENCE PROJ1_2_APP_SETTINGS_SEQ INCREMENT BY ' || TO_CHAR(max_id + 1 - next_id, 'FM99999999999999999999');
        EXECUTE IMMEDIATE 'SELECT PROJ1_2_APP_SETTINGS_SEQ.NEXTVAL FROM DUAL' INTO next_id;
    END IF;
    EXECUTE IMMEDIATE 'ALTER SEQUENCE PROJ1_2_APP_SETTINGS_SEQ INCREMENT BY 1';
    EXECUTE IMMEDIATE 'UPDATE PROJ1_2_APP_SETTINGS SET ID = PROJ1_2_APP_SETTINGS_SEQ.NEXTVAL WHERE ID IS NULL';

    FOR pk IN (SELECT CONSTRAINT_NAME FROM USER_CONSTRAINTS WHERE TABLE_NAME = 'PROJ1_2_APP_SETTINGS' AND CONSTRAINT_TYPE = 'P') LOOP
        SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY POSITION) INTO pk_columns FROM USER_CONS_COLUMNS WHERE CONSTRAINT_NAME = pk.CONSTRAINT_NAME;
        IF pk_columns = 'SETTING_KEY' THEN
            EXECUTE IMMEDIATE 'ALTER TABLE PROJ1_2_APP_SETTINGS DROP CONSTRAINT ' || DBMS_ASSERT.SIMPLE_SQL_NAME(pk.CONSTRAINT_NAME);
        ELSIF pk_columns <> 'ID' THEN
            RAISE_APPLICATION_ERROR(-20002, 'Unexpected settings primary key; inspect before continuing');
        END IF;
    END LOOP;
    SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME = 'PROJ1_2_APP_SETTINGS' AND CONSTRAINT_TYPE = 'P';
    IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE PROJ1_2_APP_SETTINGS ADD CONSTRAINT PROJ1_2_APP_SETTINGS_PK PRIMARY KEY (ID)'; END IF;
    SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'PROJ1_2_APP_SETTINGS_KEY_ID';
    IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX PROJ1_2_APP_SETTINGS_KEY_ID ON PROJ1_2_APP_SETTINGS (SETTING_KEY, ID)'; END IF;
    EXECUTE IMMEDIATE 'INSERT INTO PROJ1_2_APP_SETTINGS (ID, SETTING_KEY, PREVIOUS_VALUE, SETTING_VALUE, UPDATED_BY, UPDATED_AT)
        SELECT PROJ1_2_APP_SETTINGS_SEQ.NEXTVAL, ''export_to_sap_tab_enabled'', NULL, ''1'', ''migration'', SYS_EXTRACT_UTC(SYSTIMESTAMP)
        FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM PROJ1_2_APP_SETTINGS WHERE SETTING_KEY = ''export_to_sap_tab_enabled'')';
    COMMIT;
END;
