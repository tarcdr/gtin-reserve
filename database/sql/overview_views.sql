-- Non-destructive Overview view update. Run as the owning Oracle schema.
-- Existing columns retain their order; additional identity/parent keys are appended.
-- No tables, data, triggers or grants are dropped.
WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE OR REPLACE VIEW PROJ1_2_INDEX_SECTION_HEADER_V AS
SELECT FG_BOM, GTIN, FG_ID
FROM PROJ1_2_INDEX_SECTION_HEADER
WHERE ETS_STATUS IS NULL;

CREATE OR REPLACE VIEW PROJ1_2_INDEX_SECTION_FG_V AS
SELECT FG_ID, COMPONENTS_FG, STATUS_FG, ACTION_DETAILS, BUILT_ACTION_FG, COMPLETE_ACTION_FG, FG_BOM, GTIN
FROM PROJ1_2_INDEX_SECTION_FG;

CREATE OR REPLACE VIEW PROJ1_2_INDEX_SECTION_SFGL2_V AS
SELECT SEMI_FG_LV_2_ID, COMPONENTS_SEMI_FG_LV_2, STATUS_SEMI_FG_LV_2, ACTION_DETAILS, BUILT_ACTION_SEMI_FG_LV_2, COMPLETE_ACTION_SEMI_FG_LV_2, FG_ID, FG_BOM, GTIN
FROM PROJ1_2_INDEX_SECTION_SFGL2;

CREATE OR REPLACE VIEW PROJ1_2_INDEX_SECTION_SFGL1_V AS
SELECT SEMI_FG_LV_1_ID, COMPONENTS_SEMI_FG_LV_1, STATUS_SEMI_FG_LV_1, ACTION_DETAILS, BUILT_ACTION_SEMI_FG_LV_1, COMPLETE_ACTION_SEMI_FG_LV_1, FG_ID, FG_BOM, GTIN, SEMI_FG_LV_2_ID
FROM PROJ1_2_INDEX_SECTION_SFGL1;

CREATE OR REPLACE VIEW PROJ1_2_INDEX_SECTION_MAT4_V AS
SELECT RAW_MAT_TYPE4_ID, COMPONENTS_RAW_MAT4, STATUS_RAW_MAT4, ACTION_DETAILS, BUILT_ACTION_RAW_MAT4, COMPLETE_ACTION_RAW_MAT4, FG_ID, FG_BOM, GTIN, SEMI_FG_LV_2_ID, SEMI_FG_LV_1_ID
