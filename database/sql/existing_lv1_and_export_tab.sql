-- BOM procedure only. Install settings separately using create_app_settings.sql (new)
-- or upgrade_app_settings_history.sql (existing). This script never resets settings.
CREATE OR REPLACE PROCEDURE PROJ1_2_SAVE_BOM_SEMI_L1_EXIST(
 P_MATTYPE VARCHAR2,
 P_SUB_MATTYPE VARCHAR2,
 P_SEMI_FG_L1_BOM_ID_EXIST VARCHAR2,
 P_SEMI_FG_L1_BOM_DESC_EXIST VARCHAR2,
 P_SEMI_FG_LV1_ID_EXIST VARCHAR2,
 P_DESC_SEMI_FG_LV1_ID_EXIST VARCHAR2,
 P_FG_BOM_ID VARCHAR2,
 P_MATERIAL_ID_FG_1 VARCHAR2,
 P_SEMI_FG_L2_BOM_ID VARCHAR2,
 P_SEMI_FG_L2_ID VARCHAR2,
 P_UOM_SEMI_FG_L1ID VARCHAR2,
 P_STATUS_ROW VARCHAR2,
 P_USER_ROLE VARCHAR2,
 P_USER_LOGIN VARCHAR2,
 P_ERROR OUT VARCHAR2) IS
 n NUMBER;
BEGIN
 SAVEPOINT BOM_LINK_WRITE;
 SELECT COUNT(*) INTO n FROM PROJ1_2_DML_SEMI_L1_ID_EXIST WHERE TRIM(FG_BOM_ID)=TRIM(P_FG_BOM_ID) AND TRIM(SEMI_FG_LV2_BOM_ID)=TRIM(P_SEMI_FG_L2_BOM_ID) AND TRIM(SEMI_FG_LV1_ID_EXIST)=TRIM(P_SEMI_FG_LV1_ID_EXIST);
 IF n>0 THEN RAISE_APPLICATION_ERROR(-20001,'Existing BOM is already linked'); END IF;
 INSERT INTO PROJ1_2_DML_SEMI_L1_BOM_EXIST (NO, SEMI_FG_LV1_BOM_ID_EXIST, DESC_SEMI_FG_LV1_BOM_ID_EXIST, FG_BOM_ID, MATERIAL_ID_FG_1, SEMI_FG_LV2_BOM_ID, SEMI_FG_LV2_ID, STATUS_ROW, USER_ROLE, USER_CREATE, CREATE_DATE) VALUES (PROJ1_2_BOM_LINK_SEQ.NEXTVAL, P_SEMI_FG_L1_BOM_ID_EXIST, P_SEMI_FG_L1_BOM_DESC_EXIST, P_FG_BOM_ID, P_MATERIAL_ID_FG_1, P_SEMI_FG_L2_BOM_ID, P_SEMI_FG_L2_ID, 'INS', P_USER_ROLE, P_USER_LOGIN, SYSDATE);
 INSERT INTO PROJ1_2_DML_SEMI_L1_ID_EXIST (NO, SEMI_FG_LV1_ID_EXIST, DESC_SEMI_FG_LV1_ID_EXIST, SEMI_FG_LV1_BOM_ID_EXIST, FG_BOM_ID, MATERIAL_ID_FG_1, SEMI_FG_LV2_BOM_ID, SEMI_FG_LV2_ID, STATUS_ROW, USER_ROLE, USER_CREATE, CREATE_DATE) VALUES (PROJ1_2_BOM_LINK_SEQ.NEXTVAL, P_SEMI_FG_LV1_ID_EXIST, P_DESC_SEMI_FG_LV1_ID_EXIST, P_SEMI_FG_L1_BOM_ID_EXIST, P_FG_BOM_ID, P_MATERIAL_ID_FG_1, P_SEMI_FG_L2_BOM_ID, P_SEMI_FG_L2_ID, 'INS', P_USER_ROLE, P_USER_LOGIN, SYSDATE);
 P_ERROR := NULL;
EXCEPTION WHEN OTHERS THEN
 ROLLBACK TO BOM_LINK_WRITE;
 P_ERROR := SUBSTR(SQLERRM,1,2000);
END;
/


