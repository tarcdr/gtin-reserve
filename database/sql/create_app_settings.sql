CREATE TABLE PROJ1_2_APP_SETTINGS (
    ID             NUMBER(19,0) PRIMARY KEY,
    SETTING_KEY    VARCHAR2(100) NOT NULL,
    PREVIOUS_VALUE VARCHAR2(1),
    SETTING_VALUE  VARCHAR2(1) NOT NULL,
    UPDATED_BY     VARCHAR2(255),
    UPDATED_AT     TIMESTAMP
);

CREATE SEQUENCE PROJ1_2_APP_SETTINGS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE ORDER NOCYCLE;
CREATE INDEX PROJ1_2_APP_SETTINGS_KEY_ID ON PROJ1_2_APP_SETTINGS (SETTING_KEY, ID);

INSERT INTO PROJ1_2_APP_SETTINGS (ID, SETTING_KEY, PREVIOUS_VALUE, SETTING_VALUE, UPDATED_BY, UPDATED_AT)
VALUES (PROJ1_2_APP_SETTINGS_SEQ.NEXTVAL, 'export_to_sap_tab_enabled', NULL, '1', 'migration', SYS_EXTRACT_UTC(SYSTIMESTAMP));
COMMIT;

SELECT ID, SETTING_KEY, PREVIOUS_VALUE, SETTING_VALUE, UPDATED_BY, UPDATED_AT
FROM PROJ1_2_APP_SETTINGS
WHERE SETTING_KEY = 'export_to_sap_tab_enabled'
ORDER BY ID DESC;
